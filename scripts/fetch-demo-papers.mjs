// Downloads the CC BY 4.0 demonstration papers from Europe PMC and writes them into a server-only
// module. Email addresses are removed; author names stay for the attribution CC BY requires.
// Usage: node scripts/fetch-demo-papers.mjs
import { writeFileSync } from 'node:fs';

const PAPERS = [
  { pmcid: 'PMC7423944', doi: '10.1038/s41598-020-70651-5', publisher: 'Springer Nature' },
  { pmcid: 'PMC10422339', doi: '10.3390/polym15153239', publisher: 'MDPI' },
  { pmcid: 'PMC6836026', doi: '10.3390/polym11101614', publisher: 'MDPI' },
  { pmcid: 'PMC9572032', doi: '10.3390/polym14194035', publisher: 'MDPI' },
];

const out = [];
for (const p of PAPERS) {
  const res = await fetch(`https://www.ebi.ac.uk/europepmc/webservices/rest/${p.pmcid}/fullTextXML`);
  if (!res.ok) throw new Error(`${p.pmcid}: HTTP ${res.status}`);
  let xml = await res.text();
  if (!/creativecommons\.org\/licenses\/by\/4\.0/.test(xml)) throw new Error(`${p.pmcid}: not CC BY 4.0`);
  xml = xml
    .replace(/<email[^>]*>[\s\S]*?<\/email>/g, '')
    .replace(/<ext-link[^>]*mailto:[^>]*>[\s\S]*?<\/ext-link>/g, '')
    .replace(/[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/g, '');
  const text = (re) => (re.exec(xml)?.[1] ?? '').replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim();
  const meta = {
    title: text(/<article-title[^>]*>([\s\S]*?)<\/article-title>/),
    year: Number(text(/<pub-date[^>]*>[\s\S]*?<year>(\d{4})<\/year>/)) || null,
    venue: text(/<journal-title>([\s\S]*?)<\/journal-title>/) || null,
    abstract: text(/<abstract[^>]*>([\s\S]*?)<\/abstract>/).replace(/^Abstract\s*/i, '').slice(0, 4000) || null,
  };
  out.push({ ...p, ...meta, license: 'CC BY 4.0', source: `https://europepmc.org/article/PMC/${p.pmcid}`, xml });
}
writeFileSync(
  'server/demo/papers.generated.ts',
  `// Generated by scripts/fetch-demo-papers.mjs. CC BY 4.0 articles from Europe PMC (emails removed).\n` +
    `export interface DemoPaper { pmcid: string; doi: string; publisher: string; title: string; year: number | null; venue: string | null; abstract: string | null; license: string; source: string; xml: string }\n` +
    `export const DEMO_PAPERS: DemoPaper[] = ${JSON.stringify(out)};\n`,
);
console.log('wrote', out.length, 'papers');
